//! Boot Memory Map Representation Constants

pub const DESCRIPTOR_VERSION: u32 = 1;
pub const RUNTIME_ATTRIBUTE: u64 = 1 << 63;
pub const READ_PROTECTED_ATTRIBUTE: u64 = 1 << 13;
pub const WRITE_PROTECTED_ATTRIBUTE: u64 = 1 << 12;
pub const READ_ONLY_ATTRIBUTE: u64 = 1 << 17;
pub const LOADER_RETIREMENT_FORBIDDEN: u64 = RUNTIME_ATTRIBUTE | READ_PROTECTED_ATTRIBUTE | WRITE_PROTECTED_ATTRIBUTE | READ_ONLY_ATTRIBUTE;
